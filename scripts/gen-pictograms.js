// Regenerates src/features/vocabulary/ui/pictogramData.ts from assets/pictograms/*.svg.
// Run: node scripts/gen-pictograms.js
// Why: React Native cannot require() .svg files without an extra transformer library, so the
// markup is embedded as strings and rendered with react-native-svg's SvgXml.
/* global __dirname */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets', 'pictograms');
const out = path.join(root, 'src', 'features', 'vocabulary', 'ui', 'pictogramData.ts');

const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort();

const lines = files.map((f) => {
  const name = path.basename(f, '.svg');
  const svg = fs
    .readFileSync(path.join(dir, f), 'utf8')
    .replace(/\s*\n\s*/g, '')
    .trim();
  const key = /^[a-z][a-z0-9]*$/.test(name) ? name : JSON.stringify(name);
  return `  ${key}: ${JSON.stringify(svg)},`;
});

const header = `// GENERATED by scripts/gen-pictograms.js from assets/pictograms/*.svg. Do not edit by hand.
// Source: Figma page 03 Components, frame 3:230 (45 symbols, 96 px).
// PLACEHOLDER artwork (ARASAAC-style stand-ins), not final. See docs/figma/frame-map.md.
`;

fs.writeFileSync(
  out,
  `${header}\nexport const pictogramSvg = {\n${lines.join('\n')}\n} as const;\n`,
  'utf8',
);
console.log(`wrote ${files.length} pictograms -> ${path.relative(root, out)}`);
