// Generates assets/audio/index.ts from assets/vocabulary/audio-manifest-v1.json.
// React Native cannot require() dynamic paths, so every clip becomes a literal require().
// Usage: node scripts/gen-audio-index.js   (npm run gen:audio; also run by "prebuild")
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(
  fs.readFileSync(path.join(root, 'assets/vocabulary/audio-manifest-v1.json'), 'utf8'),
);

function block(name, map) {
  const entries = Object.entries(map || {}).map(
    ([key, rel]) => `  ${JSON.stringify(key)}: require(${JSON.stringify('../' + rel)}),`,
  );
  return `export const ${name}: Record<string, number> = {\n${entries.join('\n')}\n};\n`;
}

const out =
  '// GENERATED by scripts/gen-audio-index.js. Do not edit.\n' +
  block('wordClips', manifest.words) +
  block('messageClips', manifest.messages) +
  block('phraseClips', manifest.phrases);

fs.mkdirSync(path.join(root, 'assets/audio'), { recursive: true });
fs.writeFileSync(path.join(root, 'assets/audio/index.ts'), out);
console.log('assets/audio/index.ts written');
